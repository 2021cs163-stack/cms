import { readFileSync, writeFileSync } from "node:fs";

const shared = readFileSync(
  new URL("../supabase/functions/_shared/security.ts", import.meta.url),
  "utf8",
);
for (const name of ["manage-teacher", "send-message"]) {
  const source = readFileSync(
    new URL(`../supabase/functions/${name}/index.ts`, import.meta.url),
    "utf8",
  );
  const handler = source.replace(
    /import \{ authorize, body, headers, response \} from "\.\.\/_shared\/security\.ts";\r?\n/,
    "",
  );
  if (handler === source)
    throw new Error(`Cannot inline security import for ${name}`);
  writeFileSync(
    new URL(`../docs/${name}-dashboard.ts`, import.meta.url),
    `// Generated by scripts/bundle-functions.mjs. Deploy in the Supabase editor as ${name}.\n// Disable Verify JWT: authorize() validates the bearer token and active admin profile.\n${shared}\n${handler}`,
  );
  console.log(`Prepared docs/${name}-dashboard.ts`);
}
